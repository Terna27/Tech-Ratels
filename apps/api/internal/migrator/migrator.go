package migrator

import (
	"context"
	"fmt"
	"io/fs"
	"log"
	"sort"
	"strconv"
	"strings"

	"github.com/jackc/pgx/v5/pgxpool"
	"ratels-api/migrations"
)

// RunMigrations inspects the embedded SQL migration scripts and executes any pending
// migrations in transactional order, recording execution status in goose_db_version.
func RunMigrations(ctx context.Context, pool *pgxpool.Pool) error {
	// 1. Ensure goose_db_version tracking table exists
	createTableSQL := `
		CREATE TABLE IF NOT EXISTS goose_db_version (
			id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			version_id bigint NOT NULL,
			is_applied boolean NOT NULL,
			tstamp timestamp without time zone NOT NULL DEFAULT now()
		);
	`
	if _, err := pool.Exec(ctx, createTableSQL); err != nil {
		return fmt.Errorf("failed to create goose_db_version table: %w", err)
	}

	// 2. Query already applied version IDs
	rows, err := pool.Query(ctx, "SELECT version_id FROM goose_db_version WHERE is_applied = true")
	if err != nil {
		return fmt.Errorf("failed to query goose_db_version: %w", err)
	}
	defer rows.Close()

	applied := make(map[int64]bool)
	for rows.Next() {
		var vid int64
		if err := rows.Scan(&vid); err == nil {
			applied[vid] = true
		}
	}

	// 3. Read and sort all embedded migration files
	entries, err := fs.ReadDir(migrations.FS, ".")
	if err != nil {
		return fmt.Errorf("failed to read embedded migrations: %w", err)
	}

	type migrationFile struct {
		version  int64
		filename string
	}
	var migFiles []migrationFile

	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".sql") {
			continue
		}
		parts := strings.SplitN(entry.Name(), "_", 2)
		if len(parts) < 2 {
			continue
		}
		vid, err := strconv.ParseInt(parts[0], 10, 64)
		if err != nil {
			continue
		}
		migFiles = append(migFiles, migrationFile{
			version:  vid,
			filename: entry.Name(),
		})
	}

	sort.Slice(migFiles, func(i, j int) bool {
		return migFiles[i].version < migFiles[j].version
	})

	// 4. Apply unapplied migrations
	for _, mf := range migFiles {
		if applied[mf.version] {
			continue
		}

		content, err := migrations.FS.ReadFile(mf.filename)
		if err != nil {
			return fmt.Errorf("failed to read migration %s: %w", mf.filename, err)
		}

		upSQL := extractUpSQL(string(content))
		if strings.TrimSpace(upSQL) == "" {
			continue
		}

		log.Printf("[MIGRATION] Applying pending database migration: %s (version: %d)...\n", mf.filename, mf.version)

		tx, err := pool.Begin(ctx)
		if err != nil {
			return fmt.Errorf("failed to begin migration transaction for %s: %w", mf.filename, err)
		}

		if _, err := tx.Exec(ctx, upSQL); err != nil {
			_ = tx.Rollback(ctx)
			return fmt.Errorf("failed to execute migration %s: %w", mf.filename, err)
		}

		insertVersionSQL := "INSERT INTO goose_db_version (version_id, is_applied) VALUES ($1, true)"
		if _, err := tx.Exec(ctx, insertVersionSQL, mf.version); err != nil {
			_ = tx.Rollback(ctx)
			return fmt.Errorf("failed to record migration version %d: %w", mf.version, err)
		}

		if err := tx.Commit(ctx); err != nil {
			return fmt.Errorf("failed to commit migration transaction for %s: %w", mf.filename, err)
		}

		applied[mf.version] = true
		log.Printf("[MIGRATION] Successfully applied migration: %s\n", mf.filename)
	}

	return nil
}

// extractUpSQL extracts the portion of the migration script under "-- +goose Up"
// and before any "-- +goose Down" block.
func extractUpSQL(sqlScript string) string {
	upMarker := "-- +goose Up"
	downMarker := "-- +goose Down"

	upIdx := strings.Index(sqlScript, upMarker)
	if upIdx != -1 {
		sqlScript = sqlScript[upIdx+len(upMarker):]
	}

	downIdx := strings.Index(sqlScript, downMarker)
	if downIdx != -1 {
		sqlScript = sqlScript[:downIdx]
	}

	return strings.TrimSpace(sqlScript)
}
